import Foundation
import SwiftUI
import Combine

public final class LocalizationManager: ObservableObject {
    public static let shared = LocalizationManager()

    @Published public var currentConfiguredLanguage: String {
        didSet {
            UserDefaults.standard.set(currentConfiguredLanguage, forKey: "EnigmaSuiteConfiguredLanguage")
        }
    }

    public var effectiveLanguage: String {
        if currentConfiguredLanguage == "fi" { return "fi" }
        if currentConfiguredLanguage == "en" { return "en" }
        let preferred = Locale.preferredLanguages.first?.lowercased() ?? ""
        if preferred.starts(with: "fi") { return "fi" }
        let code = Locale.current.language.languageCode?.identifier.lowercased() ?? ""
        if code == "fi" { return "fi" }
        return "en"
    }

    public var isFinnish: Bool {
        effectiveLanguage == "fi"
    }

    private init() {
        self.currentConfiguredLanguage = UserDefaults.standard.string(forKey: "EnigmaSuiteConfiguredLanguage") ?? "auto"
    }

    public func setLanguage(_ code: String) {
        currentConfiguredLanguage = code
    }

    public func t(_ key: String) -> String {
        let lang = effectiveLanguage
        if lang == "fi", let val = stringsFI[key] {
            return val
        }
        if let val = stringsEN[key] {
            return val
        }
        return stringsFI[key] ?? key
    }
}

public func L10n(_ key: String) -> String {
    LocalizationManager.shared.t(key)
}

extension String {
    public var localized: String {
        LocalizationManager.shared.t(self)
    }
}

